//! Rendering a lockfile as its canonical v1 text (02 L1).

use toml_edit::{ArrayOfTables, DocumentMut, Item, Table, value};

use super::model::{FORMAT_VERSION, Lockfile};

/// The comment on the first line of every lockfile.
const HEADER: &str = "# This file is generated by supdoc. Do not edit by hand.\n";

impl Lockfile {
    /// The canonical text: header, `version`, `[features.hash]` with every key written out, then
    /// one `[[link]]` per entry in sorted order.
    ///
    /// The same entries always render to the same bytes. Infallible: `toml_edit` only displays
    /// documents.
    #[must_use]
    pub fn render(&self) -> String {
        let mut document = DocumentMut::new();
        set(
            document.as_table_mut(),
            "version",
            value(i64::from(FORMAT_VERSION)),
        );
        if let Some(mut version) = document.key_mut("version") {
            version.leaf_decor_mut().set_prefix(HEADER);
        }

        let mut hash = Table::new();
        hash.decor_mut().set_prefix("\n");
        set(
            &mut hash,
            "line-endings",
            value(self.hash_settings().line_endings.to_string()),
        );
        let mut features = Table::new();
        features.set_implicit(true);
        set(&mut features, "hash", Item::Table(hash));
        set(document.as_table_mut(), "features", Item::Table(features));

        if !self.is_empty() {
            let mut links = ArrayOfTables::new();
            for (key, hash) in self.iter() {
                let mut entry = Table::new();
                entry.decor_mut().set_prefix("\n");
                set(&mut entry, "source", value(key.source.as_str()));
                set(&mut entry, "target", value(key.target.to_string()));
                if let Some(symbol) = &key.symbol {
                    set(&mut entry, "symbol", value(symbol.to_string()));
                }
                set(&mut entry, "hash", value(hash.to_string()));
                links.push(entry);
            }
            set(document.as_table_mut(), "link", Item::ArrayOfTables(links));
        }
        document.to_string()
    }
}

/// Sets `key` to `item`, appending it after the keys already present.
fn set(table: &mut Table, key: &str, item: Item) {
    drop(table.insert(key, item));
}
